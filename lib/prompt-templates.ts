/** Templates of one kind for pickers. */
export function templatesFor(kind: GenerateKind): PromptTemplate[] {
  return PROMPT_TEMPLATES.filter((t) => t.kind === kind);
}

/** Find by id, undefined for unknown (pickers never get a fake template). */
export function getTemplate(id: string): PromptTemplate | undefined {
  return PROMPT_TEMPLATES.find((t) => t.id === id);
}
